CREATE TABLE publisher (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(200) NOT NULL,
    country VARCHAR2(10) NOT NULL
);

CREATE TABLE book (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    isbn VARCHAR2(32) NOT NULL UNIQUE,
    price NUMBER(10,2) NOT NULL,
    publisher_id NUMBER(19,0) NOT NULL,
    FOREIGN KEY (publisher_id) REFERENCES publisher(id)
);

CREATE TABLE customer (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(200) NOT NULL UNIQUE,
    full_name VARCHAR2(200) NOT NULL,
    loyalty_points NUMBER(19,0) NOT NULL,
    status VARCHAR2(20) NOT NULL,
    external_id VARCHAR2(36) NOT NULL UNIQUE
);

CREATE TABLE orders (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER(19,0) NOT NULL,
    status VARCHAR2(20) NOT NULL,
    placed_at TIMESTAMP NOT NULL,
    FOREIGN KEY (customer_id) REFERENCES customer(id)
);

CREATE TABLE order_item (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER(19,0) NOT NULL,
    book_id NUMBER(19,0) NOT NULL,
    quantity NUMBER(19,0) NOT NULL,
    unit_price NUMBER(10,2) NOT NULL,
    FOREIGN KEY (order_id) REFERENCES orders(id),
    FOREIGN KEY (book_id) REFERENCES book(id)
);

CREATE TABLE warehouse (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(200) NOT NULL,
    code VARCHAR2(50) NOT NULL UNIQUE,
    latitude NUMBER(9,6) NOT NULL,
    longitude NUMBER(9,6) NOT NULL
);

CREATE TABLE order_event (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id NUMBER(19,0) NOT NULL,
    event_type VARCHAR2(50) NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    FOREIGN KEY (order_id) REFERENCES orders(id)
);
